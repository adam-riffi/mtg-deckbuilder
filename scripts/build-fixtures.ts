// biome-ignore-all lint/suspicious/noExplicitAny: dev script consuming untyped Scryfall JSON
/**
 * Builds the offline fixture dataset from Scryfall's API (requires network access to api.scryfall.com).
 *   pnpm fixtures:build
 * Writes fixtures/cards.json (Scryfall card objects, one per printing) and fixtures/rulings.json.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ALL_PRINTS, FIXTURE_GROUPS, WITH_RULINGS } from "./fixture-names";

const API = "https://api.scryfall.com";
const UA =
  process.env.SCRYFALL_USER_AGENT ??
  "mtg-deckbuilder-local/0.1 (+https://github.com/adam-riffi/mtg-deckbuilder)";
const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../fixtures");
let last = 0;

async function call(url: string, body?: unknown): Promise<any> {
  const wait = last + 120 - Date.now();
  if (wait > 0) await new Promise((r) => setTimeout(r, wait));
  last = Date.now();
  const res = await fetch(url, {
    method: body ? "POST" : "GET",
    headers: {
      "User-Agent": UA,
      Accept: "application/json",
      ...(body ? { "Content-Type": "application/json" } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  if (res.status === 404) return null;
  if (!res.ok) throw new Error(`${res.status} ${url}: ${await res.text()}`);
  return res.json();
}

async function collection(identifiers: Record<string, string>[]): Promise<{ data: any[]; not_found: any[] }> {
  const data: any[] = [];
  const notFound: any[] = [];
  for (let i = 0; i < identifiers.length; i += 75) {
    const r = await call(`${API}/cards/collection`, { identifiers: identifiers.slice(i, i + 75) });
    data.push(...r.data);
    notFound.push(...r.not_found);
  }
  return { data, not_found: notFound };
}

const names = [...new Set(Object.values(FIXTURE_GROUPS).flat())];
console.log(`Fetching ${names.length} cards…`);
const byId = new Map<string, any>();
const { data, not_found } = await collection(names.map((name) => ({ name })));
for (const c of data) byId.set(c.id, c);
if (not_found.length) console.warn("Not found:", not_found.map((x) => x.name).join("; "));

// Related tokens and meld parts.
const related = new Set<string>();
for (const c of data)
  for (const p of c.all_parts ?? [])
    if (!byId.has(p.id) && (p.component === "token" || p.component.startsWith("meld"))) related.add(p.id);
console.log(`Fetching ${related.size} related tokens/parts…`);
for (const c of (await collection([...related].map((id) => ({ id })))).data) byId.set(c.id, c);

// All printings for a few cards.
for (const name of ALL_PRINTS) {
  let url: string | null =
    `${API}/cards/search?unique=prints&order=released&q=${encodeURIComponent(`!"${name}" lang:en`)}`;
  let pages = 0;
  while (url && pages < 3) {
    const r: any = await call(url);
    if (!r) break;
    for (const c of r.data) byId.set(c.id, c);
    url = r.has_more ? r.next_page : null;
    pages++;
  }
}

// Rulings.
const rulings: any[] = [];
for (const name of WITH_RULINGS) {
  const card = data.find((c) => c.name === name);
  if (!card) continue;
  const r = await call(`${API}/cards/${card.id}/rulings`);
  if (r) rulings.push(...r.data);
}

fs.mkdirSync(OUT, { recursive: true });
const cards = [...byId.values()].sort(
  (a, b) => a.name.localeCompare(b.name) || a.released_at.localeCompare(b.released_at),
);
const writeLines = (file: string, rows: unknown[]) =>
  fs.writeFileSync(path.join(OUT, file), `[\n${rows.map((r) => JSON.stringify(r)).join(",\n")}\n]\n`);
writeLines("cards.json", cards);
writeLines("rulings.json", rulings);
fs.writeFileSync(
  path.join(OUT, "README.md"),
  `# Fixture dataset\n\nGenerated by \`pnpm fixtures:build\` from the [Scryfall API](https://scryfall.com/docs/api) on ${new Date().toISOString().slice(0, 10)}.\n\n- ${cards.length} card objects (${names.length - not_found.length} requested cards plus related tokens and extra printings)\n- ${rulings.length} rulings\n\nCard data © Wizards of the Coast, provided by Scryfall. Images are not stored; they load from Scryfall's CDN.\n`,
);
console.log(`Wrote ${cards.length} cards and ${rulings.length} rulings to ${OUT}`);
